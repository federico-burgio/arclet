// Regenerate from the unpacked official lucide-static@1.67.0 npm package.
// Usage: node scripts/vendor-icons.mjs /path/to/package
import { readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import assert from 'node:assert/strict';

const directory = process.argv[2];
if (!directory) throw new Error('Pass the unpacked lucide-static package directory.');
const pkg = JSON.parse(await readFile(join(directory, 'package.json'), 'utf8'));
assert.equal(pkg.name, 'lucide-static');
assert.equal(pkg.version, '1.67.0');
const nodes = JSON.parse(await readFile(join(directory, 'icon-nodes.json'), 'utf8'));
const tags = JSON.parse(await readFile(join(directory, 'tags.json'), 'utf8'));
const ordered = object => Object.fromEntries(Object.entries(object).sort(([a], [b]) => a.localeCompare(b, 'en')));
await writeFile('src/icon-catalog.js', `// Lucide ${pkg.version}. Generated by scripts/vendor-icons.mjs. See LUCIDE-LICENSE.txt.\nexport const ICON_NODES = ${JSON.stringify(ordered(nodes))};\nexport const ICON_TAGS = ${JSON.stringify(ordered(tags))};\n`);
await writeFile('src/LUCIDE-LICENSE.txt', await readFile(join(directory, 'LICENSE')));
console.log(`Vendored ${Object.keys(nodes).length} Lucide icons with their license.`);
